#!/usr/bin/env bash
# Deploy cymbal-adk-agent (ADK AI Concierge) to Cloud Run — PRIVATE.
#   - min 1 / max 1 instances: sessions live in InMemorySessionService (single instance keeps them).
#   - invoker: cymbal-runtime SA (the site BFF proxies with its SA ID token).
#   - cymbal-runtime must also be able to invoke cymbal-commerce-mcp (granted below).
# Usage: ./deploy.sh            (env overrides: AGENT_MODEL, AGENT_THINKING_BUDGET)
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
source "${HERE}/../../config.env"   # PROJECT_ID, REGION, RUNTIME_SA, MCP_SERVICE, PATH

SERVICE="${ADK_SERVICE:-cymbal-adk-agent}"
AGENT_MODEL="${AGENT_MODEL:-gemini-3.5-flash}"
AGENT_THINKING_BUDGET="${AGENT_THINKING_BUDGET:-0}"
MCP_SERVICE="${MCP_SERVICE:-cymbal-commerce-mcp}"
MCP_URL="$(gcloud run services describe "${MCP_SERVICE}" --project "${PROJECT_ID}" --region "${REGION}" --format='value(status.url)')"
echo "MCP_URL=${MCP_URL}"

# Bake a compact catalog (id/title/tax-included price/availability/channel) into the image for cart math.
mkdir -p "${HERE}/data"
python3 - "${CATALOG_JSONL}" "${HERE}/data/products_retail.jsonl" <<'PY'
import json, sys
src, dst = sys.argv[1], sys.argv[2]

def channel_of(d):
    if d.get("channel"):
        return d["channel"]
    attrs = d.get("attributes") or []
    items = attrs if isinstance(attrs, list) else [{"key": k, "value": v} for k, v in attrs.items()]
    for a in items:
        if a.get("key") == "channel":
            v = a.get("value")
            if isinstance(v, dict):
                v = (v.get("text") or ["omni"])[0]
            return v or "omni"
    return "omni"

n = 0
with open(src, encoding="utf-8") as f, open(dst, "w", encoding="utf-8") as o:
    for line in f:
        if not line.strip():
            continue
        d = json.loads(line)
        o.write(json.dumps({"id": d["id"], "title": d.get("title", ""),
                            "priceInfo": {"price": (d.get("priceInfo") or {}).get("price", 0)},
                            "availability": d.get("availability", "IN_STOCK"),
                            "channel": channel_of(d)}, ensure_ascii=False) + "\n")
        n += 1
print(f"compact catalog: {n} products -> {dst}")
PY

# The agent's runtime SA must be able to call the private MCP server.
gcloud run services add-iam-policy-binding "${MCP_SERVICE}" --quiet \
  --project "${PROJECT_ID}" --region "${REGION}" \
  --member "serviceAccount:${RUNTIME_SA}" --role roles/run.invoker >/dev/null
# Vertex AI (Gemini): RUNTIME_SA already has roles/aiplatform.user (00_setup); not re-granted here.

gcloud run deploy "${SERVICE}" --quiet \
  --project "${PROJECT_ID}" \
  --region "${REGION}" \
  --source "${HERE}" \
  --service-account "${RUNTIME_SA}" \
  --no-allow-unauthenticated \
  --cpu 2 --memory 2Gi --cpu-boost --no-cpu-throttling \
  --min-instances 1 --max-instances 1 \
  --concurrency 40 --timeout 300 \
  --set-env-vars "GOOGLE_GENAI_USE_VERTEXAI=TRUE,GOOGLE_CLOUD_PROJECT=${PROJECT_ID},GOOGLE_CLOUD_LOCATION=global,AGENT_MODEL=${AGENT_MODEL},AGENT_THINKING_BUDGET=${AGENT_THINKING_BUDGET},MCP_URL=${MCP_URL},WARMUP_CUSTOMER_ID=CR-0001"

# The site (cymbal-site, SA cymbal-runtime) proxies to this service with its SA ID token.
gcloud run services add-iam-policy-binding "${SERVICE}" --quiet \
  --project "${PROJECT_ID}" --region "${REGION}" \
  --member "serviceAccount:${RUNTIME_SA}" --role roles/run.invoker >/dev/null

URL="$(gcloud run services describe "${SERVICE}" --project "${PROJECT_ID}" --region "${REGION}" --format='value(status.url)')"
cat > "${HERE}/DEPLOYMENT.env" <<EOF
# Generated by shared/adk_agent/deploy.sh — consumed by online-store (site proxy → ADK agent).
ADK_AGENT_URL=https://${SERVICE}-${PROJECT_NUMBER}.${REGION}.run.app
ADK_AGENT_MODEL=${AGENT_MODEL}
EOF
echo "ADK agent: ${URL}"
echo "Health   : curl -H \"Authorization: Bearer \$(gcloud auth print-identity-token)\" ${URL}/api/health"
echo "Live test: python3 ${HERE}/test_live.py"
